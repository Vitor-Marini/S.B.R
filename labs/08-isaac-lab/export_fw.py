#!/usr/bin/env python3
"""Isaac-trained residual policy (.npz from train.py) → firmware/include/rl_policy.h, and proof that the C gives the
same answers as the Python that was judged in MuJoCo (eval_in_mujoco.NpzPolicy).

    .venv/bin/python labs/08-isaac-lab/export_fw.py [model.npz]     (default: models/ppo_v11_isaac_150.npz)

The header holds the network (24 inputs → 64 tanh → 64 tanh → 1, fixed point like lab 07's export: the ESP32-C3 has
no FPU) and rl_step(): the whole v9+ control law in C, so balance.cpp only builds the frame:
    history of 3 frames → network → correction × residual → high-pass → + LQR (from the same frame) → clip ±1
"""
import os
import subprocess
import sys
import tempfile

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "..")
sys.path.insert(0, os.path.join(ROOT, "labs", "07-mujoco-rl"))
from export import iarr, q  # noqa: E402  (lab 07: Q12 weights, Q24 biases, overflow-checked int arrays)

HEADER = os.path.join(ROOT, "firmware", "include", "rl_policy.h")
DT = 0.005


def header(path):
    w = np.load(path)
    W = [w[f"W{i}"].T for i in range(3)]               # (out, in), row-major like lab 07
    b = [w[f"b{i}"] for i in range(3)]
    res, tau = float(w["residual"]), float(w["hp_tau"])
    assert W[0].shape == (64, 24) and res > 0 and tau > 0
    # Q24 sums in int32: worst case |Σ w·x| with |x| ≤ 8 (layer 1) or ≤ 1 (tanh) must stay < 2^31 / 2^24 = 128
    assert (np.abs(W[0]).sum(1) * 8).max() + np.abs(b[0]).max() < 120 and np.abs(W[1]).sum(1).max() < 120
    return f"""#pragma once
// Balancing policy trained in Isaac Lab / Newton on the GPU (labs/08-isaac-lab), generated by export_fw.py from
// {os.path.basename(path)}. Do not edit: retrain and export again. Same law as labs/08-isaac-lab/sbr_env.py (residual):
//   frame (8): (pitch − θref)/10°, rate/100 °/s, (wheel − v_ref)/0.5 m/s, (x − x_ref)/0.2 m, v_ref/0.5 m/s,
//              a_ref/1 m/s², turn ref/45 °/s, last action          — the network sees the last 3 frames (24 inputs)
//   action = clip(LQR(frame) + high-pass({res:g} × network), ±1) × 4 m/s² of wheel acceleration; high-pass τ = {tau:g} s
// FIXED POINT as in lab 07 (no FPU on the ESP32-C3): weights/activations Q12, sums Q24 in int32 (bounds checked by
// export_fw.py). Inputs beyond ±8 are clamped (pitch > 80° from the reference: already fallen).
#include <stdint.h>
#include <string.h>
#define RL_IN 24
#define RL_H 64
static const float RL_RESIDUAL = {res:.6f}f, RL_HP_TAU = {tau:.6f}f;
{iarr("RL_W1", q(W[0]), "int16_t")}{iarr("RL_B1", q(b[0], 24), "int32_t")}{iarr("RL_W2", q(W[1]), "int16_t")}{iarr("RL_B2", q(b[1], 24), "int32_t")}{iarr("RL_W3", q(W[2]), "int16_t")}{iarr("RL_B3", q(b[2], 24), "int32_t")}{iarr("RL_TANH", q(np.tanh(np.linspace(-4, 4, 257))), "int16_t")}
// tanh by table on [-4, 4] (256 steps of 1/32 = 128 in Q12) with linear interpolation; beyond: ±1
static inline int32_t rl_tanh_q(int32_t s) {{
    if (s >= 16384) return 4096;
    if (s <= -16384) return -4096;
    int32_t u = s + 16384, i = u >> 7, f = u & 127;
    return RL_TANH[i] + (((int32_t)(RL_TANH[i + 1] - RL_TANH[i]) * f) >> 7);
}}

// the network alone: 24 inputs → correction direction, clipped to ±1
static inline float rl_policy(const float in[RL_IN]) {{
    int32_t x[RL_IN], h1[RL_H], h2[RL_H];
    for (int k = 0; k < RL_IN; k++) {{
        float v = in[k] * 4096.0f;
        x[k] = v > 32767.0f ? 32767 : (v < -32767.0f ? -32767 : (int32_t)v);
    }}
    for (int i = 0; i < RL_H; i++) {{
        int32_t s = RL_B1[i];
        for (int k = 0; k < RL_IN; k++) s += RL_W1[i * RL_IN + k] * x[k];
        h1[i] = rl_tanh_q(s >> 12);
    }}
    for (int i = 0; i < RL_H; i++) {{
        int32_t s = RL_B2[i];
        for (int k = 0; k < RL_H; k++) s += RL_W2[i * RL_H + k] * h1[k];
        h2[i] = rl_tanh_q(s >> 12);
    }}
    int32_t s = RL_B3[0];
    for (int k = 0; k < RL_H; k++) s += RL_W3[k] * h2[k];
    float a = s / 16777216.0f;
    return a > 1.0f ? 1.0f : (a < -1.0f ? -1.0f : a);
}}

typedef struct {{ float hist[RL_IN]; float lp; float last; int fresh; }} rl_state_t;
static inline void rl_reset(rl_state_t *s) {{ memset(s, 0, sizeof(*s)); s->fresh = 1; }}   // each new ACTIVE session

static inline float rl_clip(float v, float lo, float hi) {{ return v < lo ? lo : (v > hi ? hi : v); }}

// one control tick. f7 = the first 7 frame entries (the 8th, last action, is kept here). Returns the action (±1).
static inline float rl_step(rl_state_t *s, const float f7[7], float dt) {{
    float f[8];
    for (int k = 0; k < 7; k++) f[k] = rl_clip(f7[k], -10.0f, 10.0f);
    f[7] = s->last;
    if (s->fresh) {{                       // like the sim's reset: the history starts as 3 copies of the first frame
        for (int k = 0; k < 3; k++) memcpy(s->hist + 8 * k, f, sizeof(f));
        s->lp = 0.0f;
        s->fresh = 0;
    }} else {{
        memmove(s->hist, s->hist + 8, 16 * sizeof(float));
        memcpy(s->hist + 16, f, sizeof(f));
    }}
    float raw = RL_RESIDUAL * rl_policy(s->hist);
    s->lp += (raw - s->lp) * (dt / RL_HP_TAU);
    // the firmware LQR (gains it was trained with) read off the same frame: sbr_env.lqr_from_obs
    float lqr = 7.44f * f[0] + 7.07f * f[1] + rl_clip(5.534f * f[3] + 7.02f * f[2] + f[5], -5.0f, 5.0f);
    float a = rl_clip(rl_clip(lqr / 4.0f, -1.0f, 1.0f) + raw - s->lp, -1.0f, 1.0f);
    s->last = a;
    return a;
}}
"""


def check(path, ticks=2000):
    """Run the C rl_step and the Python NpzPolicy (what MuJoCo judged) on the same random frame sequence."""
    sys.path.insert(0, HERE)
    import eval_in_mujoco as M
    rng = np.random.default_rng(0)
    f7 = np.cumsum(rng.normal(0, 0.05, (ticks, 7)), 0).clip(-2, 2).astype(np.float32)   # smooth, wandering frames
    p, hist, last, ref = M.NpzPolicy(path), None, 0.0, []
    for k in range(ticks):
        fr = np.append(f7[k], last).astype(np.float32)
        hist = np.tile(fr, 3) if hist is None else np.concatenate([hist[8:], fr])
        last = float(p.predict(hist)[0][0])
        ref.append(last)
    with tempfile.TemporaryDirectory() as d:
        np.savetxt(os.path.join(d, "in.txt"), f7)
        src = os.path.join(d, "t.c")
        open(src, "w").write(f'#include <stdio.h>\n#include "{HEADER}"\nint main(){{float x[7];rl_state_t s;rl_reset(&s);'
                             f'FILE*f=fopen("{d}/in.txt","r");while(fscanf(f,"%f %f %f %f %f %f %f",x,x+1,x+2,x+3,x+4,'
                             f'x+5,x+6)==7)printf("%.7f\\n",rl_step(&s,x,{DT}f));}}')
        subprocess.run(["gcc", "-O2", "-Wall", src, "-o", os.path.join(d, "t"), "-lm"], check=True)
        out = np.array(subprocess.run([os.path.join(d, "t")], capture_output=True, text=True).stdout.split(), float)
    err = np.abs(out - np.array(ref)).max()
    assert len(out) == ticks and err < 2e-2, f"C and Python differ by {err}"
    return err


if __name__ == "__main__":
    path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "models", "ppo_v11_isaac_150.npz")
    open(HEADER, "w").write(header(path))
    print("wrote", os.path.normpath(HEADER), f"({os.path.getsize(HEADER) // 1024} KB)")
    print(f"C rl_step vs Python (MuJoCo-judged) over 2000 ticks: max difference {check(path):.1e} ✓")
