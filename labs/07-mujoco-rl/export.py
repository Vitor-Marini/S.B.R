#!/usr/bin/env python3
"""Trained policy → C header for the firmware, and proof that the C math gives the same answers as PyTorch.

    .venv/bin/python labs/07-mujoco-rl/export.py [model.zip]
        → firmware/include/rl_policy.h, then compiles the same C on the PC (gcc) and compares 1000 random inputs

The network: 5 inputs → 32 tanh → 32 tanh → 1 (the action, clipped to ±1 = ±4 m/s² of wheel acceleration).
"""
import os
import subprocess
import sys
import tempfile

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "..")
HEADER = os.path.join(ROOT, "firmware", "include", "rl_policy.h")


def arr(name, a):
    flat = ", ".join(f"{v:.8e}f" for v in np.asarray(a, np.float32).flatten())
    return f"static const float {name}[{a.size}] = {{{flat}}};\n"


def q(a, bits=12):
    """Float → fixed point with `bits` fractional bits (rounded)."""
    return np.round(np.asarray(a, np.float64) * (1 << bits)).astype(np.int64)


def iarr(name, a, ctype):
    lim = 32767 if ctype == "int16_t" else 2**31 - 1
    assert np.abs(a).max() <= lim, f"{name} overflows {ctype}"
    return f"static const {ctype} {name}[{a.size}] = {{{', '.join(str(int(v)) for v in a.flatten())}}};\n"


def export(model_path):
    from stable_baselines3 import PPO
    model = PPO.load(model_path, device="cpu")
    net = model.policy.mlp_extractor.policy_net
    w1, b1 = net[0].weight.detach().numpy(), net[0].bias.detach().numpy()
    w2, b2 = net[2].weight.detach().numpy(), net[2].bias.detach().numpy()
    w3, b3 = model.policy.action_net.weight.detach().numpy(), model.policy.action_net.bias.detach().numpy()
    h = f"""#pragma once
// Balancing policy trained in MuJoCo (labs/07-mujoco-rl), generated by export.py from {os.path.basename(model_path)}.
// Do not edit: retrain and export again. Same inputs/outputs as labs/07-mujoco-rl/env.py:
//   in:  pitch/10°, rate/100 °/s, wheel speed/0.5 m/s, position error/0.2 m, last action
//   out: wheel acceleration / 4 m/s², clipped to ±1

// FIXED POINT: the ESP32-C3 has no FPU. In float this took 3.2 ms (tanhf) and still 2.2 ms with a tanh table: every
// multiply is emulated. In integers (hardware multiply) it's tens of us. Weights and activations are Q12 (×4096),
// sums of products are Q24 in int32 (weights < 1, inputs clamped to ±8: no overflow).
#include <stdint.h>
{iarr("RL_W1", q(w1), "int16_t")}{iarr("RL_B1", q(b1, 24), "int32_t")}{iarr("RL_W2", q(w2), "int16_t")}{iarr("RL_B2", q(b2, 24), "int32_t")}{iarr("RL_W3", q(w3), "int16_t")}{iarr("RL_B3", q(b3, 24), "int32_t")}{iarr("RL_TANH", q(np.tanh(np.linspace(-4, 4, 257))), "int16_t")}
// tanh by table on [-4, 4] (256 steps of 1/32 = 128 in Q12) with linear interpolation; beyond: ±1
static inline int32_t rl_tanh_q(int32_t s) {{
    if (s >= 16384) return 4096;
    if (s <= -16384) return -4096;
    int32_t u = s + 16384, i = u >> 7, f = u & 127;
    return RL_TANH[i] + (((int32_t)(RL_TANH[i + 1] - RL_TANH[i]) * f) >> 7);
}}

static inline float rl_policy(const float in[5]) {{
    int32_t x[5], h1[32], h2[32];
    for (int k = 0; k < 5; k++) {{
        float v = in[k] * 4096.0f;
        x[k] = v > 32767.0f ? 32767 : (v < -32767.0f ? -32767 : (int32_t)v);
    }}
    for (int i = 0; i < 32; i++) {{
        int32_t s = RL_B1[i];
        for (int k = 0; k < 5; k++) s += RL_W1[i * 5 + k] * x[k];
        h1[i] = rl_tanh_q(s >> 12);
    }}
    for (int i = 0; i < 32; i++) {{
        int32_t s = RL_B2[i];
        for (int k = 0; k < 32; k++) s += RL_W2[i * 32 + k] * h1[k];
        h2[i] = rl_tanh_q(s >> 12);
    }}
    int32_t s = RL_B3[0];
    for (int k = 0; k < 32; k++) s += RL_W3[k] * h2[k];
    float a = s / 16777216.0f;
    return a > 1.0f ? 1.0f : (a < -1.0f ? -1.0f : a);
}}
"""
    open(HEADER, "w").write(h)
    return model


def check(model):
    """Compile the header's rl_policy() on the PC and compare with PyTorch on 1000 random observations."""
    import torch
    rng = np.random.default_rng(0)
    obs = rng.uniform(-1.5, 1.5, (1000, 5)).astype(np.float32)
    with torch.no_grad():
        ref = np.clip(model.policy.action_net(model.policy.mlp_extractor.policy_net(torch.tensor(obs))).numpy()[:, 0], -1, 1)
    with tempfile.TemporaryDirectory() as d:
        np.savetxt(os.path.join(d, "in.txt"), obs)
        src = os.path.join(d, "t.c")
        open(src, "w").write(f'#include <stdio.h>\n#include "{HEADER}"\nint main(){{float x[5];FILE*f=fopen("{d}/in.txt","r");'
                             'while(fscanf(f,"%f %f %f %f %f",x,x+1,x+2,x+3,x+4)==5)printf("%.7f\\n",rl_policy(x));}')
        subprocess.run(["gcc", "-O2", src, "-o", os.path.join(d, "t"), "-lm"], check=True)
        out = np.array(subprocess.run([os.path.join(d, "t")], capture_output=True, text=True, cwd=d).stdout.split(), float)
    err = np.abs(out - ref).max()
    assert len(out) == 1000 and err < 1e-2, f"C and PyTorch differ by {err}"   # fixed point + table tanh
    return err


if __name__ == "__main__":
    path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "models", "ppo_balance.zip")
    m = export(path)
    print("wrote", os.path.normpath(HEADER), f"({os.path.getsize(HEADER) // 1024} KB)")
    print(f"C vs PyTorch on 1000 random inputs: max difference {check(m):.1e} ✓")
